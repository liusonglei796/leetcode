// 1) 两个独立的 if 之后又无条件 p = p.Next：
//    切换到 headB 之后又前进一格，把「对方的头节点」跳过了；
//    于是某个指针某轮多走一步，两个指针的总步数不再相等。
// 2) 为什么步数必须相等：两链相交则尾部共享，
//    走的总步数 a + c + b == b + c + a，步数相同才可能落在同一节点；
//    一旦错位就会错过交点。
// 3) 记法：nil → headB 这一步本身就是「一步」，
//    所以 if 和 else 是互斥的两条路径，不能先 if 再无条件走一步。
//
