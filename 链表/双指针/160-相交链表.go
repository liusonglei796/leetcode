package lc

// 160. 相交链表
// 双指针消除长度差：走过彼此的路 a + c + b = b + c + a，消除差值。
// 关键：两个指针每轮必须恰好走一步，总步数相同才可能落在同一节点。
//
// 正确写法
func getIntersectionNode(headA, headB *ListNode) *ListNode {
	if headA == nil || headB == nil {
		return nil
	}
	p, q := headA, headB
	for p != q {
		// if/else 是互斥的两条路径，每轮恰好走一步：
		// 沿自己的链走一步，或切换到对方的链头（nil → headB）
		if p != nil {
			p = p.Next
		} else {
			p = headB
		}
		if q != nil {
			q = q.Next
		} else {
			q = headA
		}
	}
	return p
}

